need = {"ai":96,"finance":95,"think":90,"hwpm":80,"mkt":80}
prefix_map = {"ai":"ai-","finance":"fin-","think":"think-","hwpm":"hwpm-","mkt":"mkt-"}

# 期望 id 顺延
expected = {}
for cat, base in need.items():
    expected[cat] = ["%s%03d" % (prefix_map[cat], base + i + 1) for i in range(10)]

got_ids = [c["id"] for c in NEW]
assert len(got_ids) == 50, "必须50张"
assert len(set(got_ids)) == 50, "id 必须唯一"

cat_count = {}
for i, c in enumerate(NEW):
    cid = c["id"]
    cat = c["cat"]
    cat_count[cat] = cat_count.get(cat, 0) + 1
    # 期望 id
    exp = expected[cat][cat_count[cat]-1]
    if cid != exp:
        errs.append("id 顺序错误 %s 期望 %s" % (cid, exp))
    if cid in existing_ids:
        errs.append("id 与现有重复: %s" % cid)
    if not re.match(r'^(ai|fin|think|hwpm|mkt)-\d{3}$', cid):
        errs.append("id 格式错误: %s" % cid)
    # 必填字段
    for k in ("cat","id","title","tag","question","content","points","tip","diagram","source"):
        if k not in c:
            errs.append("%s 缺字段 %s" % (cid, k))
    if c.get("diagram") not in WHITELIST:
        errs.append("%s diagram 不在白名单: %s" % (cid, c.get("diagram")))
    if not isinstance(c.get("points"), list) or len(c.get("points")) != 3:
        errs.append("%s points 必须恰3条" % cid)
    if len(c.get("title","")) > 20: errs.append("%s title 超20: %s" % (cid, len(c["title"])))
    if len(c.get("tag","")) > 6: errs.append("%s tag 超6" % cid)
    if len(c.get("question","")) > 30: errs.append("%s question 超30: %s" % (cid, len(c["question"])))
    if len(c.get("content","")) > 80: errs.append("%s content 超80: %s" % (cid, len(c["content"])))
    if len(c.get("tip","")) > 30: errs.append("%s tip 超30: %s" % (cid, len(c["tip"])))
    if len(c.get("source","")) > 25: errs.append("%s source 超25" % cid)

# 各分类恰好10张
for cat in ("ai","finance","think","hwpm","mkt"):
    if cat_count.get(cat,0) != 10:
        errs.append("%s 张数=%s 应为10" % (cat, cat_count.get(cat,0)))

if errs:
    print("❌ 校验失败:")
    for e in errs: print("  -", e)
    sys.exit(1)

